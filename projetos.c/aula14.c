#include <stdio.h>
//Operadores Relacionais em c
int main() {

    int a = 10;
    int b = 20;

    printf("a > b: %d\n", a > b);  //Maior que 
    printf("a < b: %d\n", a < b);  //Menor que
    printf("a == b: %d\n", a == b); //Igual a 
    printf("a != b: %d\n", a != b); //Diferente de

    return 0;


}